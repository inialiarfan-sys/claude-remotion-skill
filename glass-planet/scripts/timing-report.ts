/** Print + write src/data/timing-report.md (scene start/end from the real audio). */
import { writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { buildTimeline } from '../src/lib/timeline';

let audio: number | undefined;
try {
  audio = parseFloat(execSync('npx remotion ffprobe -v error -show_entries format=duration -of csv=p=0 public/narration.mp3').toString());
} catch {
  audio = undefined;
}
const tl = buildTimeline(audio);
const f = (s: number) => `${Math.floor(s / 60)}:${(s % 60).toFixed(2).padStart(5, '0')}`;
const rows = tl.scenes.map(
  (s, i) => `| ${i + 1} | ${s.title} | “${s.anchor}” | ${f(s.start)} | ${f(s.end)} | ${(s.end - s.start).toFixed(1)}s | ${s.found ? (s.score * 100).toFixed(0) + '%' : '**missing — placed proportionally**'} |`,
);
const md = `# Timing report

Generated by \`npm run timing\` from \`src/data/transcript.json\` (real audio, not the script).

- Audio length: **${tl.duration.toFixed(2)} s** → composition length **${tl.total.toFixed(2)} s** (${Math.ceil(tl.total * 30)} frames @ 30 fps)
- Scenes start when their anchor phrase starts being spoken (fuzzy match) and end when the next one starts.
- Scene 1 starts at 0:00 so the cold open ("The worst planet ever discovered") is part of it.
${tl.missing.length ? `- ⚠️ Missing anchors: ${tl.missing.map((m) => `“${m}”`).join(', ')}` : '- All 16 anchors found.'}

| # | Scene | Anchor | Start | End | Length | Match |
|---|---|---|---|---|---|---|
${rows.join('\n')}
`;
writeFileSync('src/data/timing-report.md', md);
console.log(md);
if (tl.missing.length) console.warn('WARNING: missing anchors →', tl.missing.join(' | '));
