import React from 'react';
import { CalculateMetadataFunction, Composition, staticFile } from 'remotion';
import { getAudioData, getAudioDurationInSeconds } from '@remotion/media-utils';
import { alignLines, detectSpeech } from './align';
import { SCRIPT } from './script';
import { countWords } from './timing';
import { DiamondRain, DiamondRainProps } from './DiamondRain';
import { buildTimeline } from './timing';

const FPS = 30;

/**
 * Auto-time everything from public/narration.mp3 when it exists:
 * length = audio + 1 s, and every line is snapped to where it is actually spoken
 * (pauses detected in the waveform). Falls back to a word-count split if the
 * audio can't be matched, and to ~2.5 words/second with no audio at all.
 */
const calculateMetadata: CalculateMetadataFunction<DiamondRainProps> = async () => {
  let audioSeconds: number | null = null;
  let aligned: [number, number][] | null = null;
  try {
    const src = staticFile('narration.mp3');
    audioSeconds = await getAudioDurationInSeconds(src);
    try {
      const data = await getAudioData(src);
      const segs = detectSpeech(data.channelWaveforms[0], data.sampleRate);
      aligned = alignLines(
        SCRIPT.flatMap((s) => s.lines).map((l) => countWords(l.text)),
        segs,
      );
    } catch {
      aligned = null; // decoding failed → word-count timing
    }
  } catch {
    audioSeconds = null; // no narration.mp3 → estimate from word count
  }
  const timeline = buildTimeline(audioSeconds, FPS, aligned);
  // Score + SFX are generated by `npm run audio` (runs automatically before dev/render).
  let music = false;
  try {
    await getAudioDurationInSeconds(staticFile('audio/score.wav'));
    music = true;
  } catch {
    music = false;
  }
  console.info(`[diamond-rain] narration timing: ${timeline.timing}, music: ${music}`);
  return { durationInFrames: timeline.totalFrames, props: { timeline, music } };
};

const defaultProps: DiamondRainProps = { timeline: buildTimeline(null, FPS) };

export const RemotionRoot: React.FC = () => (
  <>
    <Composition
      id="DiamondRainVertical"
      component={DiamondRain}
      width={1080}
      height={1920}
      fps={FPS}
      durationInFrames={defaultProps.timeline.totalFrames}
      defaultProps={defaultProps}
      calculateMetadata={calculateMetadata}
    />
    <Composition
      id="DiamondRainWide"
      component={DiamondRain}
      width={1920}
      height={1080}
      fps={FPS}
      durationInFrames={defaultProps.timeline.totalFrames}
      defaultProps={defaultProps}
      calculateMetadata={calculateMetadata}
    />
  </>
);
